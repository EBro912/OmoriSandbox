	private SpriteFrames BuildEnemyAnimation(JsonEnemyMod jsonEnemy, string path, ModLoadReport report)
	{
		if (!FileAccess.FileExists($"{path}/{jsonEnemy.Atlas}"))
		{
			report.Error("enemies", jsonEnemy.Name, $"Atlas file not found: {jsonEnemy.Atlas}");
			return null;
		}
		Image image = Image.LoadFromFile($"{path}/{jsonEnemy.Atlas}");
		if (image == null)
		{
			report.Error("enemies", jsonEnemy.Name, $"Failed to load atlas image: {jsonEnemy.Atlas}");
			return null;
		}
		Texture2D texture = ImageTexture.CreateFromImage(image);
		int width = jsonEnemy.Width;
		int height = jsonEnemy.Height;
		if (width > texture.GetWidth() || height > texture.GetHeight())
		{
			report.Error("enemies", jsonEnemy.Name, $"Atlas dimensions ({texture.GetWidth()}x{texture.GetHeight()}) smaller than frame size ({width}x{height})");
			return null;
		}
		int columns = texture.GetWidth() / width;
		SpriteFrames spriteFrames = new();
		foreach (JsonModAnimationData data in jsonEnemy.Animation)
		{
			spriteFrames.AddAnimation(data.Emotion);
			spriteFrames.SetAnimationSpeed(data.Emotion, data.Fps);
			spriteFrames.SetAnimationLoop(data.Emotion, true);
			foreach (int idx in data.Frames)
			{
				int column = idx % columns;
				int row = idx / columns;
				AtlasTexture tex = new()
				{
					Atlas = texture,
					Region = new Rect2(column * width, row * height, width, height)
				};
				spriteFrames.AddFrame(data.Emotion, tex);
			}
		}
		return spriteFrames;
	}

	private void LoadBGM(string root, ModLoadReport report)
	{
		string path = "user://mods/" + root + "/bgm";
		foreach (string file in DirAccess.GetFilesAt(path))
		{
			if (file.EndsWith(".ogg"))
			{
				if (!AudioManager.Instance.LoadCustomBGM($"{path}/{file}"))
				{
					report.Error("bgm", file, "Failed to load custom BGM");
					report.CountSkipped();
				}
				else
				{
					report.CountLoaded();
				}
			}
		}
	}


